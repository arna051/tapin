export type TapinErrorOrigin = 'platform' | 'postal' | 'unknown';
export const describeTapinCode = (code: number, origin: TapinErrorOrigin = 'unknown') => {
  const key = String(code);
  if (origin === 'platform') return tapinPlatformMessages[key];
  if (origin === 'postal') return tapinPostalMessages[key];
  return tapinPlatformMessages[key] ?? tapinPostalMessages[key];
};
